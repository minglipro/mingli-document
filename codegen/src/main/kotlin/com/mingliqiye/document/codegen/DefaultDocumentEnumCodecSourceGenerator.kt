package com.mingliqiye.document.codegen

/**
 * [DocumentEnumCodecSourceGenerator] 默认实现。
 *
 * 生成的转换器按枚举 `name` 写出、按 `valueOf` 读入，非法名称返回 `null`；
 * 生成的模块在 `setupModule` 中注册全部转换器。
 */
public class DefaultDocumentEnumCodecSourceGenerator : DocumentEnumCodecSourceGenerator {

    override fun converterSource(spec: DocumentEnumCodecSpec): String {
        val enumType = spec.enumQualifiedName
        return buildString {
            appendLine("// Generated by mingli-document KSP codegen. Do not edit.")
            appendLine("@file:Suppress(\"unused\", \"UNUSED_PARAMETER\")")
            appendLine()
            appendLine("package ${spec.converterPackage}")
            appendLine()
            appendLine("import com.mingliqiye.document.core.DocumentTypeReference")
            appendLine("import com.mingliqiye.document.core.Node")
            appendLine("import com.mingliqiye.document.core.StringNode")
            appendLine("import com.mingliqiye.document.serialization.DeserializationContext")
            appendLine("import com.mingliqiye.document.serialization.DocumentBaseConverter")
            appendLine("import com.mingliqiye.document.serialization.SerializationContext")
            appendLine()
            appendLine("public class ${spec.converterName} : DocumentBaseConverter<$enumType> {")
            appendLine()
            appendLine("    override fun getType(): DocumentTypeReference<$enumType> = DocumentTypeReference.of($enumType::class.java)")
            appendLine()
            appendLine("    override fun serialize(value: $enumType, context: SerializationContext): Node = StringNode.of(value.name)")
            appendLine()
            appendLine("    override fun deserialize(node: Node, context: DeserializationContext): $enumType? = try {")
            appendLine("        $enumType.valueOf(node.asString())")
            appendLine("    } catch (_: Exception) {")
            appendLine("        null")
            appendLine("    }")
            appendLine("}")
        }
    }

    override fun moduleSource(spec: DocumentModuleSpec): String = buildString {
        appendLine("// Generated by mingli-document KSP codegen. Do not edit.")
        appendLine("@file:Suppress(\"unused\")")
        appendLine()
        appendLine("package ${spec.packageName}")
        appendLine()
        appendLine("import com.mingliqiye.document.serialization.DocumentModule")
        appendLine("import com.mingliqiye.document.serialization.ModuleSetupContext")
        appendLine()
        appendLine("public class ${spec.moduleName} : DocumentModule {")
        appendLine()
        appendLine("    override val moduleName: String = \"${spec.moduleName}\"")
        appendLine()
        appendLine("    override fun setupModule(context: ModuleSetupContext) {")
        for (converter in spec.converters) {
            appendLine("        context.addConverter($converter())")
        }
        appendLine("    }")
        appendLine("}")
    }
}
